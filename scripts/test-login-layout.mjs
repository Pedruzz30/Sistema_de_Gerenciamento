import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const html=await readFile('src/main/resources/static/login.html','utf8');
const css=await readFile('src/main/resources/static/app.css','utf8');
const build=await readFile('scripts/build-preview.mjs','utf8');
const inline=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(inline);
for(const id of ['loginForm','senhaForm','nome','sobrenome','senha','authEmail','legacyNameFields','supabaseEmailField','btnSubmit','alert','alertMsg','alertIcon','novaSenha','confirmarSenha','novoPin','pinCampo','senhaAviso','senhaFormNome'])assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1);
assert.match(html,/onsubmit="handleLogin\(event\)"/);
assert.match(html,/onsubmit="handleCriarSenha\(event\)"/);
assert.match(html,/id="senhaForm"[^>]*hidden/);
assert.match(html,/id="senha"[^>]*type="password"|type="password" id="senha"/);
assert.match(html,/<!-- STOCKOS_PREVIEW_ENTRY -->/);
assert.doesNotMatch(html,/Abrir demonstração sem login|100%|Conexão segura/);
assert.match(html,/<details class="login-ajuda"><summary>Esqueceu a senha/);
assert.match(css,/body\.login-page \.card-head\{display:block/);
assert.match(css,/body\.login-page #senhaForm\[hidden\]/);
assert.match(css,/#senhaForm:not\(\[hidden\]\)~\.stockos-demo-entry\{display:none!important/);
assert.match(css,/@media\(max-width:760px\)/);
const block=build.slice(build.indexOf("  if(page==='login.html'){"),build.indexOf('  await writeFile(p,html);',build.indexOf("  if(page==='login.html'){")));
const preview=new Function('html','page',block+'\nreturn html;')(html,'login.html');
assert.ok(preview.indexOf('class="stockos-demo-entry"')>preview.indexOf('</form>',preview.indexOf('id="loginForm"')));
assert.equal((preview.match(/class="stockos-demo-entry"/g)||[]).length,1);
assert.match(preview,/href="\/dashboard.html">Abrir demonstração sem login/);
assert.equal(new Function('html','page',block+'\nreturn html;')(html,'estoque.html'),html);
assert.doesNotMatch(preview,/<!-- STOCKOS_PREVIEW_ENTRY -->/);
console.log('PASS login layout, preserved auth selectors and preview-only entry placement.');
