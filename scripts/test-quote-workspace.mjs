import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile('src/main/resources/static/js/cotacoes.js','utf8');
const html=await readFile('src/main/resources/static/cotacoes.html','utf8');
const css=await readFile('src/main/resources/static/css/cotacoes-refinement.css','utf8');
new vm.Script(source);
const api=vm.runInNewContext(source.slice(source.indexOf('const quoteNorm='),source.indexOf('let todosProdutos='))+'\n({quoteNumber,quoteMonth,quotePrevious,quoteMoney,quoteReportModel,quoteHistoryModel,quoteProducts,quoteInput});');
assert.equal(api.quoteNumber('12.50'),12.5);
assert.equal(api.quoteNumber(''),null);
assert.equal(api.quoteNumber('0x12'),null);
assert.equal(api.quoteNumber(null),null);
assert.equal(api.quotePrevious('2026-01'),'2025-12');
assert.equal(api.quoteMonth('2026-13'),false);
assert.match(api.quoteMoney(20165.81),/R\$\s*20\.165,81/);
const records=[{produtoId:1,produtoNome:'Água',precoAnterior:'10.00',precoAtual:'12.00',variacaoAbsoluta:'2.00',variacaoPercentual:'20.00',tendencia:'SUBIU'},{produtoId:2,produtoNome:'Café',precoAnterior:20,precoAtual:18,variacaoAbsoluta:-2,variacaoPercentual:-10,tendencia:'caiu'},{produtoId:3,produtoNome:'Arroz',precoAnterior:'8',precoAtual:'8',variacaoAbsoluta:'0',variacaoPercentual:'0',tendencia:'ESTAVEL'}];
const m=api.quoteReportModel(records);
assert.equal(m.total,3);
assert.equal(m.counts.SUBIU,1);
assert.equal(m.counts.CAIU,1);
assert.equal(m.counts.ESTAVEL,1);
assert.equal(m.rows[0].current,12);
assert.equal(api.quoteReportModel(records,'agua').count,1);
assert.equal(api.quoteReportModel(records,'','CAIU').rows[0].id,'2');
assert.equal(api.quoteReportModel(records,'','','low').rows[0].id,'2');
assert.equal(api.quoteReportModel(records,'','','name').rows[0].id,'1');
assert.equal(api.quoteReportModel([], '', '', 'high').total,0);
assert.equal(api.quoteReportModel(null),null);
const big=Array.from({length:1600},(_,i)=>({...records[0],produtoId:i+1}));
assert.equal(api.quoteReportModel(big).rows.length,15);
assert.equal(api.quoteReportModel(big,'','','high',999).page,107);
assert.equal(api.quoteReportModel(big,'','','high',999).rows.length,10);
const h=api.quoteHistoryModel([{mes:'2026-10',precoUnitario:'10.00',quantidadeComprada:2,gastoTotal:'20.00'},{mes:'2026-11',precoUnitario:'12.00',quantidadeComprada:3,gastoTotal:'36.00'}]);
assert.equal(h.latest.price,12);
assert.equal(h.change,20);
assert.equal(h.latest.total,36);
assert.equal(api.quoteHistoryModel([{mes:'2026-09',precoUnitario:'10'},{mes:'2026-11',precoUnitario:'12'}]).change,null);
assert.equal(api.quoteProducts([{id:1,nome:'Água',codigoBarras:'12345'}],'agua').length,1);
assert.equal(api.quoteProducts([{id:1,nome:'Água',codigoBarras:'12345'}],'12345').length,1);
assert.equal(api.quoteInput('1','2026-11','12.50','2').precoUnitario,'12.50');
assert.equal(api.quoteInput('1','2026-11','12.50','2.5'),null);
assert.equal(api.quoteInput('1','2026-11','12.501','2'),null);
assert.equal(api.quoteInput('1','2026-11','0','2'),null);
assert.equal(api.quoteInput('1','2026-11','12','2147483648'),null);
assert.match(source,/version===reportVersion/);
assert.match(source,/version===historyVersion/);
assert.match(source,/registerPending\|\|registerUncertain/);
assert.match(source,/escapeHtml\(c\.name\)/);
assert.match(html,/id="quote-pagination" hidden/);
assert.match(html,/id="quote-history-search"/);
assert.match(css,/\.quote-filters\{display:grid/);
console.log('PASS quote workspace: decimal strings, comparison filters, 1600-item pagination, consecutive month history, validation and stale-response guards.');
