import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile('src/main/resources/static/js/logs.js','utf8');
const html=await readFile('src/main/resources/static/logs.html','utf8');
const css=await readFile('src/main/resources/static/css/logs-refinement.css','utf8');
new vm.Script(source);
const api=vm.runInNewContext(source.slice(source.indexOf('const AUDIT_LIMIT='),source.indexOf('let todosLogs='))+'\n({auditDate,auditAction,auditModel});');
assert.equal(api.auditDate('25/11/2026 12:19:00').day,'2026-11-25');
assert.equal(api.auditDate('2026-11-25T12:19:00').time,'12:19:00');
assert.equal(api.auditDate('31/02/2026 12:00:00'),null);
assert.equal(api.auditDate('29/02/2024 12:00:00').day,'2024-02-29');
assert.equal(api.auditDate('25/11/2026 24:00:00'),null);
assert.equal(api.auditDate('2026-13-01T10:00:00'),null);
assert.equal(api.auditDate('bad'),null);
assert.equal(api.auditAction('CAIXA_ABERTO'),'Caixa aberto');
const data=[{id:1,usuarioRu:1,acao:'CAIXA_ABERTO',descricao:'Operação',dataHora:'25/11/2026 12:19:00'},{id:2,usuarioRu:null,acao:'ESTOQUE_CONFERIDO',dataHora:'26/11/2026 10:00:00'},{id:3,usuarioRu:1,acao:'VENDA_REGISTRADA',dataHora:'2026-11-24T10:00:00'},{id:4,usuarioRu:12,acao:'TESTE',dataHora:'bad'}];
const m=api.auditModel(data);
assert.equal(m.total,4);
assert.equal(m.users.length,2);
assert.equal(m.system,1);
assert.equal(m.latest.day,'2026-11-26');
assert.equal(m.rows[0].id,'2');
assert.equal(m.rows[3].id,'4');
assert.equal(api.auditModel(data,{sort:'old'}).rows[0].id,'3');
assert.equal(api.auditModel(data,{query:'operacao'}).count,1);
assert.equal(api.auditModel(data,{user:'1'}).count,2);
assert.equal(api.auditModel(data,{user:'system'}).count,1);
assert.equal(api.auditModel(data,{action:'CAIXA_ABERTO',user:'1',from:'2026-11-25',to:'2026-11-25'}).count,1);
assert.equal(api.auditModel(data,{from:'2026-11-25'}).count,2);
assert.equal(api.auditModel(data,{from:'2026-11-26',to:'2026-11-25'}).validRange,false);
assert.equal(api.auditModel(data,{action:'CAIXA_ABERTO'}).total,4);
assert.equal(api.auditModel([],{}).latest,null);
assert.equal(api.auditModel(null),null);
const big=Array.from({length:2000},(_,i)=>({...data[0],id:i+1}));
assert.equal(api.auditModel(big).rows.length,15);
assert.equal(api.auditModel(big,{},999).page,134);
assert.equal(api.auditModel(big,{},999).rows.length,5);
assert.equal(api.auditModel(big,{},1,50).rows.length,50);
assert.match(source,/fetch\('\/api\/logs\?limit='\+AUDIT_LIMIT\)/);
assert.match(source,/token===version/);
assert.match(source,/esc\(v\.action\|\|/);
assert.match(source,/esc\(v\.description/);
assert.match(source,/get\('audit-detail-description'\)\.textContent/);
assert.match(html,/id="audit-detail"/);
assert.match(css,/\.audit-filters\{display:grid/);
console.log('PASS audit workspace: real/preview timestamps, filters, unknown dates, read-only event details and bounded pagination.');
