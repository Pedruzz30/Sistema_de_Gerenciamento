import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile('src/main/resources/static/js/estoque.js','utf8');
const html=await readFile('src/main/resources/static/estoque.html','utf8');
const css=await readFile('src/main/resources/static/css/estoque-refinement.css','utf8');
new vm.Script(source);
const cats=source.slice(source.indexOf('const CATEGORIAS_ESTOQUE ='),source.indexOf('async function iniciarEstoqueSPA'));
const api=vm.runInNewContext(cats+source.slice(source.indexOf('function productCreateQuantity('),source.indexOf('let productCreatePending='))+'\n({productCreateQuantity,productCreatePrice,productCreateStock,productCreateInput});');
assert.equal(api.productCreateQuantity('0'),0);
assert.equal(api.productCreateQuantity('1.5'),null);
assert.equal(api.productCreateQuantity('1e3'),null);
assert.equal(api.productCreateQuantity('-1'),null);
assert.equal(api.productCreateQuantity(''),null);
assert.equal(api.productCreateQuantity('2147483647'),2147483647);
assert.equal(api.productCreateQuantity('2147483648'),null);
assert.equal(api.productCreatePrice('0'), '0');
assert.equal(api.productCreatePrice('7,50'),'7.50');
assert.equal(api.productCreatePrice('7.501'),null);
assert.equal(api.productCreatePrice('1e2'),null);
assert.equal(api.productCreatePrice('-1'),null);
assert.equal(api.productCreatePrice(''),null);
assert.equal(api.productCreateStock(0,0).level,'SEM_ESTOQUE');
assert.equal(api.productCreateStock(1,0).level,'ADEQUADO');
assert.equal(api.productCreateStock(25,100).level,'CRITICO');
assert.equal(api.productCreateStock(50,100).level,'BAIXO');
assert.equal(api.productCreateStock(75,100).level,'MODERADO');
assert.equal(api.productCreateStock(76,100).level,'ADEQUADO');
assert.equal(api.productCreateStock(25,100).deficit,75);
assert.equal(api.productCreateStock(100,25).deficit,0);
assert.equal(api.productCreateStock(null,0),null);
const fields={nome:' Água ',initial:'12',minimum:'24',price:'2.50',category:'BEBIDAS'};
assert.equal(api.productCreateInput(fields).nome,'Água');
assert.equal(api.productCreateInput(fields).precoUnitario,'2.50');
assert.equal(api.productCreateInput(fields).quantidadeInicial,12);
assert.equal(api.productCreateInput({...fields,category:''}).categoriaEstoque,null);
assert.equal(api.productCreateInput({...fields,category:'INVALIDA'}),null);
assert.equal(api.productCreateInput({...fields,nome:' '}),null);
assert.equal(api.productCreateInput({...fields,nome:'a'.repeat(121)}),null);
assert.equal(api.productCreateInput({...fields,initial:'2.5'}),null);
assert.match(source,/productCreatePending\|\|productCreateUncertain\|\|!temPermissao/);
assert.match(source,/if\(id==='modal-cadastro'&&productCreatePending\)return/);
assert.match(source,/result\.nome\.trim\(\)!==payload\.nome/);
assert.match(source,/productCreateUncertain=true;mostrarAlertaModal/);
assert.match(html,/id="product-create-submit"[^>]*disabled/);
assert.match(html,/id="product-check-stock" hidden/);
assert.match(css,/\.product-stock-preview\{display:grid/);
for(const id of ['c-nome','c-categoria','c-qtd-inicial','c-qtd-minima','c-preco','alert-cadastro'])assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1);
console.log('PASS product registration: integer quantities, decimal price, stock prediction, permissions and guarded submission.');
