import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile,access} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';

const modelFile='preview-source/js/comandas-demo-model.js';
const pageFile='preview-source/js/comandas-demo.js';
for(const f of [modelFile,pageFile,'scripts/build-preview.mjs'])execFileSync(process.execPath,['--check',f],{stdio:'inherit'});
const context={window:{},Date,Map,Number,String,JSON,Error,Array,console};
vm.createContext(context);
vm.runInContext(await readFile(modelFile,'utf8'),context);
const model=context.window.StockOSComandasDemoModel.createModel();
const beverage={id:7,nome:'Água mineral 500ml',precoUnitario:4,quantidadeAtual:12,ativo:true};
const juice={id:8,nome:'Suco de uva 1L',precoUnitario:12.9,quantidadeAtual:5,ativo:true};
const opened=model.open('27');
assert.equal(opened.numero,27);
assert.equal(opened.status,'ABERTA');
assert.throws(()=>model.open('27'),/já existe/);
assert.throws(()=>model.open('99999'),/entre 1 e 9999/);
assert.throws(()=>model.requestClose(27),/Adicione produtos/);
model.add(27,beverage,3);
model.add(27,juice,2);
assert.equal(model.get(27).totalCentavos,3780);
assert.equal(model.get(27).quantidade,5);
assert.throws(()=>model.add(27,juice,4),/estoque/);
model.change(27,7,-1,12);
assert.equal(model.get(27).totalCentavos,3380);
model.requestClose(27);
assert.equal(model.get(27).status,'CONFERENCIA');
assert.throws(()=>model.add(27,beverage,1),/Retome/);
assert.throws(()=>model.change(27,7,1,12),/Retome/);
model.resume(27);
model.change(27,7,1,12);
assert.equal(model.get(27).totalCentavos,3780);
const restored=context.window.StockOSComandasDemoModel.createModel(JSON.parse(JSON.stringify(model.list())));
assert.equal(restored.get(27).totalCentavos,3780);
assert.equal(restored.get(27).status,'ABERTA');
assert.deepEqual(restored.list().map(t=>t.numero),[27]);

const ui=await readFile(pageFile,'utf8');
assert.doesNotMatch(ui,/\/api\/(?:vendas|caixas|saas|pagamentos|estoque)\b/);
assert.match(ui,/window\.StockOSComandasDemoModel\.createModel/);
assert.match(ui,/localStorage\.setItem/);
assert.match(ui,/model\.requestClose/);
assert.match(ui,/model\.resume/);
assert.match(ui,/aria-pressed/);
const html=await readFile('preview-source/comandas-demo.html','utf8');
assert.match(html,/Nenhum pagamento/);
assert.match(html,/id="open-tab"/);
assert.match(html,/id="product-list"/);
assert.match(html,/id="order-list"/);
execFileSync(process.execPath,['scripts/build-preview.mjs'],{stdio:'inherit'});
for(const path of ['comandas-demo.html','js/comandas-demo.js','js/comandas-demo-model.js','css/comandas-demo.css'])await access('dist-preview/'+path);
await assert.rejects(access('dist-preview/saas-comandas.html'));
const routes=await readFile('dist-preview/_redirects','utf8');
assert.match(routes,/^\/comandas-demo \/comandas-demo\.html 200$/m);
console.log('PASS comandas demo: open, duplicate prevention, consumption, cents, stock limit, conference, resume, isolation and output');
