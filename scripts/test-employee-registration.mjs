import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile('src/main/resources/static/js/funcionarios.js','utf8');
const html=await readFile('src/main/resources/static/funcionarios.html','utf8');
const css=await readFile('src/main/resources/static/css/funcionarios-refinement.css','utf8');
new vm.Script(source);
const api=vm.runInNewContext(source.slice(source.indexOf('const EMPLOYEE_ROLE_ACCESS='),source.indexOf('let employeeCreatePending='))+'\n({employeeCpfMask,employeeCpfValid,employeePasswordValid,employeeCreateInput,EMPLOYEE_ROLE_ACCESS});',{TextEncoder});
assert.equal(api.employeeCpfMask('52998224725'),'529.982.247-25');
assert.equal(api.employeeCpfValid('529.982.247-25'),true);
assert.equal(api.employeeCpfValid('52998224724'),false);
assert.equal(api.employeeCpfValid('11111111111'),false);
assert.equal(api.employeeCpfValid('123'),false);
assert.equal(api.employeePasswordValid('abc'),false);
assert.equal(api.employeePasswordValid('123456'),false);
assert.equal(api.employeePasswordValid('aaaaaa'),false);
assert.equal(api.employeePasswordValid(' '),false);
assert.equal(api.employeePasswordValid('é'.repeat(37)+'a'),false);
assert.equal(api.employeePasswordValid('A1b2C3d4'),true);
const sample={nome:' João ',sobrenome:' Silva ',cpf:'529.982.247-25',senha:'A1b2C3d4',nomeClasse:'CAIXA'};
assert.equal(api.employeeCreateInput(sample).nome,'João');
assert.equal(api.employeeCreateInput(sample).cpf,'52998224725');
assert.equal(api.employeeCreateInput({...sample,nomeClasse:'SUPERIOR'}),null);
assert.equal(api.employeeCreateInput({...sample,nomeClasse:'SUPERIOR',confirmed:true}).nomeClasse,'SUPERIOR');
assert.equal(api.employeeCreateInput({...sample,nomeClasse:'toString'}),null);
assert.equal(api.EMPLOYEE_ROLE_ACCESS.SUPERIOR.permissions.length,7);
assert.equal(api.EMPLOYEE_ROLE_ACCESS.GERENTE_ESTOQUE.permissions.length,6);
assert.equal(api.EMPLOYEE_ROLE_ACCESS.ESTOQUISTA.permissions.length,2);
assert.equal(api.EMPLOYEE_ROLE_ACCESS.CAIXA.permissions.length,2);
assert.match(source,/if\(employeeCreatePending\|\|employeeCreateUncertain\)return/);
assert.match(source,/employeeCreateUncertain=true;employeeGet\('c-senha'\)\.value=''/);
assert.match(source,/employeeHidePassword\(\);employeeGet\('c-senha'\)\.value=''/);
assert.match(html,/aria-labelledby="employee-create-title"/);
assert.match(html,/autocomplete="new-password"/);
assert.match(html,/id="employee-elevated-wrap" hidden/);
assert.match(css,/\.employee-create-grid\{display:grid/);
for(const id of ['c-nome','c-sobrenome','c-cpf','c-senha','c-classe','alert-cadastro','employee-create-submit'])assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1);
